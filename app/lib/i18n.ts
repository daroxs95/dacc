export type Lang = "es" | "en";
export type MessageKey = keyof typeof messages;
export const LANGUAGE_STORAGE_KEY = "dacc.interfaceLanguage";

export function resolveLanguage(saved: string | null, preferred: readonly string[]): Lang {
  if (saved === "es" || saved === "en") return saved;
  for (const locale of preferred) {
    const base = locale.toLowerCase().split("-")[0];
    if (base === "es" || base === "en") return base;
  }
  return "en";
}

export function translate(language: Lang, key: MessageKey, values: Record<string, string | number> = {}): string {
  const template = language === "es" ? messages[key] : key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    values[name] === undefined ? placeholder : String(values[name]));
}

export function errorKey(error: unknown): MessageKey {
  const message = error instanceof Error ? error.message : "";
  return Object.hasOwn(messages, message) ? message as MessageKey : "The database operation failed.";
}

// Existing invoices use dollars; localization changes presentation, not stored currency.
export function formatMoney(language: Lang, value: number): string {
  return new Intl.NumberFormat(language, {style: "currency", currency: "USD"}).format(value);
}
